// Writes docs/portfolio/demo-data.js: the real element data the portfolio prototypes embed.
// Run: node tools/portfolio-data.mjs

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { root } from './net.mjs';

const core = JSON.parse(await readFile(join(root, 'public/data/elements.json'), 'utf8'));
const photos = JSON.parse(await readFile(join(root, 'public/data/photos.json'), 'utf8'));

const FAMILY_COLOR = {
  alkali: '#e2654f', alkaline: '#e8973a', transition: '#d9b451', post: '#86a35f', metalloid: '#3f9a8a',
  nonmetal: '#3f8fc4', halogen: '#6a74cf', noble: '#9a6cc2', lanthanide: '#cf6f94', actinide: '#b8595f', unknown: '#7d7a73',
};

const elements = core.elements.map((e) => {
  const p = photos.elements[String(e.z)];
  return {
    z: e.z, symbol: e.symbol, es: e.name.es, en: e.name.en, x: e.x, y: e.y, shells: e.shells, family: e.family,
    mass: e.mass, hero: p?.hero || null, medium: p?.medium || null, artist: p?.artist || null, license: p?.license || null,
  };
});

const out = `// Generated by tools/portfolio-data.mjs from public/data/elements.json and photos.json. Do not edit.\nwindow.MATERIA = ${JSON.stringify({ built: core.built, FAMILY_COLOR, elements })};\n`;
await mkdir(join(root, 'docs/portfolio'), { recursive: true });
await writeFile(join(root, 'docs/portfolio/demo-data.js'), out);
console.log(`demo-data.js: ${elements.length} elements, ${Buffer.byteLength(out)} bytes`);
